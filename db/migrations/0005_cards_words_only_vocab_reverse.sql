-- 0005 · Колода = только слова; грамматика уезжает в упражнения. Плюс reverse-карточки.
--
-- Причина. Колея 1 (SRS) собирала три типа заметок: vocab, grammar_cloze
-- (авторские cloze_cards из theory.yaml) и transformation (дубликат уже
-- существующих key_word_transformation упражнений). Это смешивало два разных
-- режима работы: «вспомнить атом» (карточка) и «решить задание» (упражнение),
-- причём grammar_cloze ещё и показывался с невырезанной Anki-разметкой
-- {{c1::…}}, из-за чего ответ был виден на лицевой стороне.
--
-- Новое разделение (утверждено владельцем 2026-07-20):
--   колея 1 — только лексика, по две карточки на слово (узнавание term→definition
--             и воспроизведение definition→term, каждая со своим SRS-графиком);
--   колея 2 — все задания, включая бывшие cloze_cards: sync теперь синкает их
--             как open_cloze упражнения в review-пул модуля, откуда они
--             попадают в квизы и — при ошибке — в очередь +2/+7/+21 д.
--
-- Прогресс. Ничего не удаляется: карточки помечаются archived, card_state и
-- ссылки error_map_entry.flashcard_id остаются на месте, а
-- listDueCards/countDueCards уже фильтруют по archived=false — карточки просто
-- перестают выпадать. Откат решения вернёт их вместе с расписанием.
--
-- Архивируются и карточки, собранные пользователем из своих ошибок
-- (source='error_harvest'): их note_type — те же grammar_cloze/transformation,
-- которые приложение больше не рендерит, так что оставить их активными значит
-- уронить плеер на первой же такой карточке. Сама ошибка при этом не теряется —
-- она остаётся в error_map_entry и в очереди колеи 2.

begin;

-- Направление «definition → term». Отдельная строка, а не режим показа:
-- узнавание и воспроизведение — разные навыки, и SRS должен вести их
-- независимо (отменяет решение D9 в ARCHITECTURE.md).
alter type note_type add value if not exists 'vocab_reverse';

-- Карточки-задания. Контентные sync снял бы и сам
-- (archiveRemovedFlashcards), но harvest-карточки он не трогает — у них нет
-- ident'а, — поэтому состояние фиксируется здесь, до первого синка.
update flashcard
   set archived = true
 where archived = false
   and note_type in ('grammar_cloze', 'transformation');

-- Сбросить гейт-хеш модулей (ARCHITECTURE.md §4.4). Он считается от сырых
-- байтов YAML-пакета, а изменилась не разметка контента, а то, что sync из
-- неё выводит: те же cloze_cards теперь дают упражнения, те же vocab-записи —
-- по две карточки. Без сброса sync увидел бы совпадение хешей и пропустил
-- каждый модуль с нулём запросов — и на билде Netlify тоже.
update module m
   set content_hash = null
  from block b, course c
 where m.block_id = b.id
   and b.course_id = c.id
   and c.slug = 'en-c1';

commit;
